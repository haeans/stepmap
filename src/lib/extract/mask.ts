// AI에 보내기 전에 원문 속 개인정보를 가린다. (B18)
// Gemini 무료 등급은 보낸 내용을 서비스 개선에 쓰고 사람이 볼 수 있다.
// 이메일, 전화번호, 카드 번호처럼 모양이 정해진 값만 가린다. 이름·예약번호는 가릴 수 없으므로 화면에서 안내한다.

const RULES: [RegExp, string][] = [
  [/[\w.+-]+@[\w-]+(\.[\w-]+)+/g, "[이메일]"],
  [/\b\d{6}[- ]?[1-4]\d{6}\b/g, "[주민등록번호]"],
  [/\b\d{4}[- ]?\d{4}[- ]?\d{4}[- ]?\d{3,4}\b/g, "[카드번호]"],
  [/(\+\d{1,3}[- .]?)?\(?0?\d{1,3}\)?[- .]\d{3,4}[- .]\d{4}\b/g, "[전화번호]"],
  [/\b[A-Z]{1,2}\d{7,8}\b/g, "[여권번호]"],
];

export function maskPersonal(text: string): string {
  return RULES.reduce((out, [re, label]) => out.replace(re, label), text);
}
